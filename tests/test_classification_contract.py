def test_empty_history_allows_only_no_match() -> None:
    data = make_inputs().model_dump()
    data["retrieval"]["families"] = ()
    data["retrieval"]["bm25_family_ids"] = ()
    data["retrieval"]["dense_family_ids"] = ()
    data["retrieval"]["fused_family_ids"] = ()
    data["current_heads"] = ()
    request = prepare_request(ClassificationInput.model_validate(data))
    assert request.output_schema["properties"]["matched_requirement_id"]["enum"] == [None]
    assert decode_output(prediction("new", None), request).matched_requirement_id is None
    with pytest.raises(ClassificationOutputError):
        decode_output(prediction(), request)


@pytest.mark.parametrize("authority,replacement", [(False, True), (True, False), (False, False)])
def test_supersession_needs_independent_authority_and_replacement_guards(
    authority: bool, replacement: bool
) -> None:
    inputs = make_inputs()
    output = decode_output(prediction(), prepare_request(inputs))
    verdict = assess_classification(
        inputs, output, speaker_can_confirm_scope=authority, replacement_stated=replacement
    )
    assert verdict.verdict == Verdict.UNRESOLVED
    assert verdict.proposed_event is None


def test_adapter_uses_authoritative_state_without_mutating_inputs() -> None:
    inputs = make_inputs()
    snapshot = inputs.model_dump()
    output = decode_output(prediction(), prepare_request(inputs))
    verdict = assess_classification(
        inputs, output, speaker_can_confirm_scope=True, replacement_stated=True
    )
    assert verdict.verdict == Verdict.ALLOWED
    assert verdict.proposed_event == EventType.SUPERSEDE
    assert verdict.resulting_state == State.SUPERSEDED
    assert inputs.model_dump() == snapshot
    # Allowed means validation passed; it is not confirmation or a register write.


def test_adapter_rejects_changed_retrieval_provenance_and_non_boolean_guards() -> None:
    inputs = make_inputs()
    output = decode_output(prediction(), prepare_request(inputs))
    output.retrieved_ids = ["INVENTED"]
    with pytest.raises(ClassificationOutputError, match="provenance"):
        assess_classification(
            inputs, output, speaker_can_confirm_scope=True, replacement_stated=True
        )
    output = decode_output(prediction(), prepare_request(inputs))
    with pytest.raises(ValueError, match="booleans"):
        assess_classification(
            inputs,
            output,
            speaker_can_confirm_scope="false",  # type: ignore[arg-type]
            replacement_stated=True,
        )


def test_mutated_nested_candidate_is_rechecked() -> None:
    inputs = make_inputs()
    inputs.candidate.evidence.clear()
    with pytest.raises(ValidationError, match="source evidence"):
        prepare_request(inputs)
